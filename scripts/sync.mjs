function renderAgentInstructions(config, sourceContent) {
  const body = sourceContent.endsWith('\n') ? sourceContent : `${sourceContent}\n`
  return `# GENERATED by ohmydsh scripts/sync.mjs — do not edit by hand.\n# Source: ${config.source} (configured by dsh.yaml).\n\n${body}`
}

async function syncAgentInstructions(config, { reset = false } = {}) {
  const state = await loadState()
  const managed = state.agentInstructions
  const target = path.join(DSH_HOME, 'AGENTS.md')
  const targetExists = existsSync(target)

  if (reset || config === undefined || !config.enabled) {
    if (!targetExists) {
      if (managed !== undefined) {
        delete state.agentInstructions
        await saveState(state)
        change('clear stale agentInstructions state (target absent)')
      }
      return
    }
    if (managed === undefined) {
      log(`agent instructions unmanaged at ${target}; leaving in place`)
      return
    }
    const currentHash = contentHash(await readFile(target))
    if (typeof managed.deployedHash !== 'string' || currentHash !== managed.deployedHash) {
      fail(`agent instructions drift at ${target}; refusing to remove changed managed content`)
      return
    }
    change(`remove managed agent instructions ${target}`)
    await rm(target)
    delete state.agentInstructions
    await saveState(state)
    return
  }

  let sourceStat
  try {
    sourceStat = await stat(config.sourcePath)
  } catch {
    fail(`agentInstructions.source missing: ${config.source}`)
    return
  }
  if (!sourceStat.isFile()) {
    fail(`agentInstructions.source must be a file: ${config.source}`)
    return
  }

  const actualSourcePath = await realpath(config.sourcePath)
  const actualRepoPath = await realpath(REPO)
  const actualRelative = path.relative(actualRepoPath, actualSourcePath)
  if (actualRelative === '..' || actualRelative.startsWith(`..${path.sep}`) || path.isAbsolute(actualRelative)) {
    fail(`agentInstructions.source resolves outside the repository: ${config.source}`)
    return
  }

  const desired = renderAgentInstructions(config, await readFile(actualSourcePath, 'utf8'))
  const desiredHash = contentHash(desired)
  if (targetExists) {
    const currentHash = contentHash(await readFile(target))
    if (managed === undefined) {
      if (currentHash !== desiredHash) {
        fail(`agent instructions target is unmanaged at ${target}; refusing to overwrite existing content`)
        return
      }
      change(`adopt matching agent instructions ${target}`)
    } else {
      if (typeof managed.deployedHash !== 'string' || currentHash !== managed.deployedHash) {
        fail(`agent instructions drift at ${target}; refusing to overwrite changed managed content`)
        return
      }
      if (currentHash === desiredHash) {
        log('agent instructions up-to-date')
        return
      }
      change(`update agent instructions ${target}`)
      await atomicWrite(target, desired)
    }
  } else {
    if (managed !== undefined) {
      delete state.agentInstructions
      await saveState(state)
      log('cleared stale agentInstructions state before deployment')
    }
    change(`generate agent instructions ${target}`)
    await atomicWrite(target, desired)
  }

  state.agentInstructions = { source: config.source, deployedHash: desiredHash }
  await saveState(state)
}

/**
 * Bundle-less support packages from the top-level `dependencies` list:
 * install / pin / remove as plain profile dependencies. Never join the
 * bundle layer stack (`dsh plugin add` reconciliation already keeps
 * bundle-less packages out); state tracking mirrors managedPackages.
 */
async function syncDependencies(manifest) {
  const state = await loadState()
  const currentNames = new Set(manifest.deps.map((d) => d.name))
  const previousNames = state.managedDependencies ?? []
  for (const name of previousNames) {
    if (currentNames.has(name)) continue
    if (installedVersion(name) !== undefined) {
      change(`remove dependency ${name}`)
      if (!dshCli(['plugin', '--profile', PROFILE, 'remove', name], { version: manifest.dshVersion })) fail(`failed to remove dependency ${name}`)
    }
  }
  for (const dep of manifest.deps) {
    const current = installedVersion(dep.name)
    if (current !== undefined && current !== dep.version) {
      change(`dependency drift ${dep.name} ${current} -> ${dep.version}, re-adding`)
      if (!dshCli(['plugin', '--profile', PROFILE, 'add', `${dep.name}@${dep.version}`], { version: manifest.dshVersion })) fail(`failed to pin dependency ${dep.name}`)
    } else if (current === undefined) {
      change(`install dependency ${dep.name} (${dep.spec})`)
      if (!dshCli(['plugin', '--profile', PROFILE, 'add', dep.spec], { version: manifest.dshVersion })) fail(`failed to install dependency ${dep.name}`)
    } else {
      log(`dependency ${dep.name}@${current} up-to-date`)
    }
  }
  state.managedDependencies = [...currentNames]
  await saveState(state)
}

async function syncPackages(manifest, items, names) {
  // Entries resolvePackageNames skipped (disabled, source absent) are handled
  // exactly like entries deleted from the manifest.
  const packages = items.filter((i) => i.type === 'package' && names.has(i.id))
  const enabled = packages.filter((i) => i.enabled)
  const profilePkgPath = path.join(PROFILE_DIR, 'package.json')
  const profilePkg = readJson(profilePkgPath)
  if (profilePkg === undefined) return fail(`profile package.json missing at ${PROFILE_DIR}`)

  const enabledNames = enabled.map((i) => names.get(i.id)).filter(Boolean)
  const state = await loadState()
  const previousCompatByOwner = state.managedCompatDependencies ?? {}
  const compatByOwner = new Map()
  const claimedCompatNames = new Set()
  for (const item of packages) {
    const owner = names.get(item.id)
    if (owner === undefined) continue
    const entries = item.compatDependencies ?? []
    for (const entry of entries) {
      if (claimedCompatNames.has(entry.name) || [...names.values()].includes(entry.name)) {
        fail(`local package ${owner}: compatibility dependency name ${entry.name} is not uniquely owned`)
        continue
      }
      claimedCompatNames.add(entry.name)
    }
    compatByOwner.set(owner, entries)
  }

  // Local package specs embed the absolute checkout path. Repair stale paths
  // before any plugin command so a moved/renamed repository cannot make pnpm
  // fail while reconciling an otherwise unrelated package.
  let repairedLocalSpecs = false
  profilePkg.dependencies ??= {}
  for (const item of enabled.filter((entry) => entry.source === 'local')) {
    const name = names.get(item.id)
    const expected = `file:${sourceDirOf(item, 'packages')}`
    if (name !== undefined && profilePkg.dependencies[name] !== expected) {
      change(`local package path ${name} -> ${expected}`)
      profilePkg.dependencies[name] = expected
      repairedLocalSpecs = true
    }
  }
  if (repairedLocalSpecs) await writeJson(profilePkgPath, profilePkg)

  // Remove a disabled owner and every compatibility override it owns in one
  // pnpm transaction. This restores DSH's install-anchor fallback without a
  // window where the bundle is active against the wrong Connection package.
  for (const [id, name] of names) {
    const item = packages.find((i) => i.id === id)
    if (item.enabled) continue
    const compatNames = [...new Set([
      ...(compatByOwner.get(name) ?? []).map(entry => entry.name),
      ...(previousCompatByOwner[name] ?? []),
    ])]
    const removal = [name, ...compatNames].filter(packageName =>
      profilePkg.dependencies?.[packageName] !== undefined || installedVersion(packageName) !== undefined)
    if (removal.length > 0) {
      change(`remove disabled package ${name}${compatNames.length > 0 ? ' with compatibility overrides' : ''}`)
      if (!dshCli(['plugin', '--profile', PROFILE, 'remove', ...removal], { version: manifest.dshVersion })) {
        fail(`failed to remove ${removal.join(', ')}`)
      } else {
        delete previousCompatByOwner[name]
      }
    } else {
      delete previousCompatByOwner[name]
    }
  }

  // remove entries deleted from the manifest (previously managed, now absent);
  // names now managed as top-level dependencies are not ours to remove
  const depNames = new Set(manifest.deps.map((d) => d.name))
  const currentNames = new Set(names.values())
  const previousNames = state.managedPackages ?? []
  for (const name of previousNames) {
    if (currentNames.has(name) || depNames.has(name)) continue
    const compatNames = previousCompatByOwner[name] ?? []
    const removal = [name, ...compatNames].filter(packageName =>
      profilePkg.dependencies?.[packageName] !== undefined || installedVersion(packageName) !== undefined)
    if (removal.length > 0) {
      change(`remove deleted package ${name}${compatNames.length > 0 ? ' with compatibility overrides' : ''}`)
      if (!dshCli(['plugin', '--profile', PROFILE, 'remove', ...removal], { version: manifest.dshVersion })) {
        fail(`failed to remove ${removal.join(', ')}`)
      } else {
        delete previousCompatByOwner[name]
      }
    } else {
      delete previousCompatByOwner[name]
    }
  }
  state.managedPackages = [...currentNames]
  await saveState(state)

  // Local file dependencies are copied into the profile rather than symlinked.
  // Build from source before any remove/reinstall, then compare only publishable
  // bytes. Build-input and install-content identities are deliberately separate.
  const previousLocalHashes = state.localPackageHashes ?? {}
  const previousBuildInputs = state.localPackageBuildInputs ?? {}
  // What the last successful build actually PRODUCED: `{ input, output }` per
  // package, where `output` is the publishable content hash of the artifacts
  // that build emitted. Distinct from `localPackageBuildInputs`, which records
  // the input of the last successful DEPLOYMENT and therefore answers "did the
  // source move since we last shipped", never "are these the outputs we built".
  //
  // Recording the OUTPUT rather than where or from what it was built is
  // deliberate, and was reached by falsifying two indirect designs during
  // implementation: keying on the source hash alone cannot tell one checkout's
  // artifacts from another's built from identical source (the 2026-09-08
  // shape), and adding the source directory still missed artifacts replaced in
  // place. Both proxied "what produced it" for "what it is", and a proxy
  // always leaves a way around it. The bytes do not.
  //
  // This does not require reproducible builds: it records what a build DID
  // emit, not what a source SHOULD emit, so nondeterminism in the output is
  // irrelevant as long as nobody replaced it afterwards.
  //
  // Absent (older ledger, `dsh reset`) means unprovable, which forces a build.
  const previousBuiltFrom = state.localPackageBuiltFrom ?? {}
  /** Whether the recorded build output still matches what is on disk. */
  const builtOutputMatches = (record, output) =>
    record !== undefined &&
    record !== null &&
    typeof record === 'object' &&
    record.output === output
  const previousCompatHashes = state.compatDependencyHashes ?? {}
  // Packages proven incomplete at their source, keyed by the identity that was
  // proven bad (local content hash / remote spec). Keeping the identity means a
  // new version or a fixed tarball is retried automatically.
  const previousUnrepairable = state.unrepairablePackages ?? {}
  const nextUnrepairable = {}
  const enabledNameSet = new Set(enabledNames)
  // Preserve the last successful ledger for enabled owners across a failed
  // rebuild. Their deployed profile bytes remain intact, so erasing these
  // hashes would cause a needless replacement after the fixed input is restored.
  const nextLocalHashes = Object.fromEntries(Object.entries(previousLocalHashes)
    .filter(([packageName]) => enabledNameSet.has(packageName)))
  const nextBuildInputs = Object.fromEntries(Object.entries(previousBuildInputs)
    .filter(([packageName]) => enabledNameSet.has(packageName)))
  // Carried for the same reason, but it tracks a different fact: the source
  // `lib/` survives a failed deployment untouched, so what built it is still
  // true and must not be forgotten. Rewritten per package as builds succeed.
  const nextBuiltFrom = Object.fromEntries(Object.entries(previousBuiltFrom)
    .filter(([packageName]) => enabledNameSet.has(packageName)))
  const enabledCompatNames = new Set(enabled.flatMap(item =>
    (item.compatDependencies ?? []).map(entry => entry.name)))
  const nextCompatHashes = Object.fromEntries(Object.entries(previousCompatHashes)
    .filter(([packageName]) => enabledCompatNames.has(packageName)))
  const nextManagedCompat = Object.fromEntries(Object.entries(previousCompatByOwner)
    .filter(([packageName]) => enabledNameSet.has(packageName)))
  for (const item of enabled) {
    const name = names.get(item.id)
    const localDir = item.source === 'local' ? sourceDirOf(item, 'packages') : undefined
    const currentCompatNames = (compatByOwner.get(name) ?? []).map(entry => entry.name)
    const removedCompatNames = (previousCompatByOwner[name] ?? [])
      .filter(packageName => !currentCompatNames.includes(packageName))
    if (removedCompatNames.length > 0) {
      // Dropping SOME overrides while keeping others is the dangerous shape
      // this guard exists for: the owner still runs against a partially
      // replaced dependency tree, and which half it gets is install order.
      //
      // Retiring the LAST one is different in kind. The owner has stopped
      // requesting overrides at all, so restoring the official packages is the
      // whole point rather than an accident, and there is no mixed tree to land
      // in. Reinstalling the owner in the same pnpm transaction is what makes
      // it a real retirement instead of leaving the replaced copies deployed.
      if (currentCompatNames.length > 0) {
        fail(`local package ${name}: refusing to remove or rename active compatibility overrides (${removedCompatNames.join(', ')}); disable the owner and sync first`)
        continue
      }
      change(`local package ${name} retired its compatibility overrides (${removedCompatNames.join(', ')}); restoring official packages`)
      if (!dshCli(['plugin', '--profile', PROFILE, 'remove', ...removedCompatNames], { version: manifest.dshVersion })) {
        fail(`failed to retire compatibility overrides for ${name}`)
        continue
      }
      delete previousCompatByOwner[name]
      for (const packageName of removedCompatNames) delete nextCompatHashes[packageName]
    }
    const spec = localDir === undefined ? item.spec : `file:${localDir}`
    let localHash
    let buildInputHash
    if (localDir !== undefined) {
      const localPkg = readJson(path.join(localDir, 'package.json'))
      buildInputHash = await localBuildInputHash(localDir, item.buildInputs ?? [], item.sourceRoot ?? REPO)
      const buildable = typeof localPkg?.scripts?.build === 'string'
      const outputsPresent = localBuildOutputsExist(localDir, localPkg)
      // Hash the artifacts BEFORE deciding, so the decision can rest on what
      // they actually are. The first two conditions below only describe the
      // input side — whether the source moved since the last deployment, and
      // whether outputs exist at all — and neither can rule out outputs that
      // exist but are not the ones this build produced.
      //
      // Unprovable rebuilds rather than assumes. The alternative failed
      // silently: sync skipped the build, then the deployment check compared
      // the stale deployed copy against the equally stale source artifact,
      // found them identical, and shipped it with exit code 0.
      const currentOutput = buildable && outputsPresent
        ? await localInstallContentHash(localDir)
        : undefined
      const needsBuild = buildable && (
        previousBuildInputs[name] !== buildInputHash ||
        !outputsPresent ||
        !builtOutputMatches(nextBuiltFrom[name], currentOutput)
      )
      if (needsBuild) {
        // Drop the claim BEFORE building: a build that dies partway leaves
        // outputs of unknown provenance, and a surviving record would certify
        // them as current on the next run — making this defect permanent.
        delete nextBuiltFrom[name]
        if (!runLocalBuild(item, localDir)) continue
      }
      if (!localBuildOutputsExist(localDir, localPkg)) {
        fail(`local package ${name}: build outputs are missing after build readiness check`)
        continue
      }
      localHash = await localInstallContentHash(localDir)
      // Recorded on build success, not deployment success: it describes the
      // source artifacts, which exist regardless of whether deployment later
      // succeeds. Tying it to deployment would rebuild needlessly after any
      // deployment failure. `localHash` is the same publishable-content hash
      // the comparison above uses, so the two can never drift apart.
      if (buildable && needsBuild) nextBuiltFrom[name] = { input: buildInputHash, output: localHash }
    }
    const compatEntries = localDir === undefined ? [] : (compatByOwner.get(name) ?? [])
    const compatSpecs = []
    const compatHashes = {}
    // Source-side provenance per compatibility artifact, compared below against
    // what is actually deployed. A content hash cannot stand in for this: the
    // hash only answers "did the source bytes change since the last sync we
    // recorded", and a ledger entry that survives while the deployed copy came
    // from an older upstream base makes the two agree on a lie.
    const compatProvenance = {}
    let compatInvalid = false
    for (const entry of compatEntries) {
      const compatDir = path.join(localDir, entry.path)
      const compatPkg = readJson(path.join(compatDir, 'package.json'))
      if (compatPkg?.name !== entry.name) {
        fail(`local package ${name}: compatibility artifact ${entry.path} must declare name ${entry.name}`)
        compatInvalid = true
        break
      }
      compatSpecs.push(`file:${compatDir}`)
      compatHashes[entry.name] = await dirHash(compatDir)
      compatProvenance[entry.name] = compatProvenanceOf(compatPkg)
    }
    if (compatInvalid) continue

    const current = installedVersion(name)
    const currentlyInstalledFrom = installedSpec(name)
    // A remoted pin change must trigger re-install even when the package version
    // is unchanged: bumping the spec commit is exactly how a fork patch update
    // deploys, and sync previously only compared version. Only tarball/URL specs
    // are compared this way: pnpm stores a plain version for registry specs
    // (`name@version` is normalized away), so comparing those here would falsely
    // drift every registry package. Registry drift stays covered by the version
    // compare below.
    const pinSpec = typeof item.spec === 'string'
      && typeof item.name === 'string'
      && (/^(?:https?:|git\+|file:)/.test(item.spec) || /\.(?:tar\.gz|tgz)($|\?)/.test(item.spec))
    const pinDrift = item.source === 'remote'
      && current !== undefined
      && pinSpec
      && currentlyInstalledFrom !== undefined
      && currentlyInstalledFrom !== item.spec
    // Provenance drift is deployment-side truth, read from the installed copy
    // rather than from the ledger. The ledger only remembers what sync last
    // wrote; it cannot see a deployed artifact that was built from a different
    // upstream base — which is exactly how the profile's storage overlays sat a
    // whole version family behind the launcher's while every name, path and
    // recorded hash still matched (see `checking/baseline-compat-identity.md`).
    const compatDrifted = compatEntries.filter(entry => {
      if (installedVersion(entry.name) === undefined) return false
      const expected = compatProvenance[entry.name]
      if (expected === undefined) return false
      const deployed = compatProvenanceOf(readJson(deployedPackageJsonPath(entry.name)))
      return deployed !== undefined && deployed !== expected
    })
    const compatChanged = compatDrifted.length > 0 || compatEntries.some(entry =>
      installedVersion(entry.name) === undefined || previousCompatHashes[entry.name] !== compatHashes[entry.name])
    // Deployment-side integrity. Every other trigger here compares metadata
    // (version / source hash / recorded spec) and so cannot see a package that
    // is installed but incomplete. Checked for local and remote alike: an
    // interrupted install truncates either one the same way.
    const missingFiles = current === undefined ? [] : missingDeployedFiles(name)
    // A package whose *source* cannot satisfy its own manifest (an incomplete
    // published tarball, e.g. the dsh-cockpit-bridge@0.1.0 incident recorded in
    // dsh.yaml) is unrepairable by reinstalling. Once proven so for this exact
    // identity, report it and stop: re-running the install every sync would
    // churn a network fetch forever without ever converging.
    // Identity of what was proven incomplete. Must be stable across runs, so it
    // is derived from the manifest (source hash / declared spec+version) rather
    // than from the deployed state, which differs between the first install and
    // later runs. A new version or a re-published tarball changes it and the
    // package is retried automatically.
    const repairIdentity = item.source === 'local' ? `local:${localHash}` : `remote:${item.spec}@${item.version}`
    let installed = true
    if (missingFiles.length > 0 && previousUnrepairable[name] === repairIdentity) {
      fail(`${name} is incomplete at its source and cannot be repaired by reinstalling (missing ${missingFiles.join(', ')}); pin a fixed version or disable it`)
      nextUnrepairable[name] = repairIdentity
      installed = false
    } else if (missingFiles.length > 0) {
      change(`incomplete deployment ${name}: missing ${missingFiles.join(', ')}, reinstalling`)
      // Two stages, ordered so a failure can never destroy a working deployment.
      // Stage 1 is a plain re-add: cheap, transactional, and enough whenever the
      // package manager will re-materialize the tree.
      installed = dshCli(['plugin', '--profile', PROFILE, 'add', ...compatSpecs, spec], { version: manifest.dshVersion })
      if (!installed) {
        fail(`failed to repair incomplete deployment of ${name}`)
      } else if (missingDeployedFiles(name).length > 0) {
        // Stage 2. pnpm keys a `file:` dependency on the source directory's
        // identity, so with the manifest already satisfied it re-links the same
        // truncated tree and stage 1 changes nothing. Evicting the deployed copy
        // forces a fresh materialization — but only now that stage 1 has proven
        // the install itself succeeds, so this cannot strand a package that was
        // merely degraded. Restore the evicted tree if the retry fails.
        const deployedDir = path.join(PROFILE_DIR, 'node_modules', ...name.split('/'))
        const quarantine = `${deployedDir}.ohmydsh-recovering`
        await rm(quarantine, { recursive: true, force: true })
        await rename(deployedDir, quarantine).catch(() => {})
        installed = dshCli(['plugin', '--profile', PROFILE, 'add', ...compatSpecs, spec], { version: manifest.dshVersion })
        const stillMissing = installed ? missingDeployedFiles(name) : []
        if (!installed || stillMissing.length > 0) {
          if (!existsSync(deployedDir) && existsSync(quarantine)) {
            await rename(quarantine, deployedDir).catch(() => {})
            log(`restored previous deployment of ${name} after failed repair`)
          }
          installed = false
          // Remember the identity so the next run reports instead of retrying.
          nextUnrepairable[name] = repairIdentity
          fail(stillMissing.length > 0
            ? `deployment of ${name} still missing after reinstall: ${stillMissing.join(', ')}`
            : `failed to repair incomplete deployment of ${name}`)
        }
        await rm(quarantine, { recursive: true, force: true })
      }
    } else if (pinDrift) {
      change(`spec drift ${name} ${currentlyInstalledFrom} -> ${item.spec}, re-adding`)
      installed = dshCli(['plugin', '--profile', PROFILE, 'add', item.spec], { version: manifest.dshVersion })
    } else if (current !== undefined && item.source === 'remote' && current !== item.version) {
      change(`version drift ${name} ${current} -> ${item.version}, re-adding`)
      installed = dshCli(['plugin', '--profile', PROFILE, 'add', item.spec], { version: manifest.dshVersion })
      if (!installed) fail(`failed to pin ${name}`)
    } else if (item.source === 'local' && (
      current === undefined || current !== item.version || previousLocalHashes[name] !== localHash || compatChanged
    )) {
      if (current === undefined) {
        change(`install local package ${name} (${spec})`)
        installed = dshCli(['plugin', '--profile', PROFILE, 'add', ...compatSpecs, spec], { version: manifest.dshVersion })
        if (!installed) fail(`failed to install ${name}`)
      } else if (previousLocalHashes[name] !== localHash && !compatChanged) {
        // Content drift. pnpm `file:` directory dependencies merge without
        // overwriting existing subtree files, so a plain re-add may leave the
        // deployed copy stale while the source-side hash says "current".
        // Verify the DEPLOYED bytes: already matching means the drift was
        // deployed by other means (manual refresh, previous repair) — record
        // the hash and move on; mismatching forces an atomic refresh.
        const deployedHash = await deployedContentHash(readJson(path.join(localDir, 'package.json')), name)
        if (deployedHash === localHash) {
          log(`package ${name}@${current} content changed, deployment already matches source`)
          installed = true
        } else {
          change(`local package ${name} content changed, reinstalling atomically`)
          // Evict-then-add so the deployed copy cannot keep stale subtree
          // files; refresh re-verifies and restores the old copy on failure.
          installed = await refreshLocalDeployment(localDir, name, spec, compatSpecs, localHash, manifest.dshVersion)
          if (!installed) fail(`failed to refresh deployment of ${name}`)
        }
      } else {
        // Version pin drift or a compatibility artifact change: same install
        // mechanics as before (the atomic refresh path above owns content).
        // Name provenance drift explicitly. It is the one trigger here whose
        // cause is invisible in the manifest and the ledger alike, so reporting
        // it as a generic "artifact changed" would hide exactly the condition
        // that made the drift survivable in the first place.
        const reason = current !== item.version
          ? `${current} -> ${item.version}`
          : compatDrifted.length > 0
            ? `deployed compatibility overrides were built from a different upstream base (${compatDrifted.map(e => e.name).join(', ')})`
            : 'compatibility artifact changed'
        const action = `local package ${name} ${reason}, reinstalling atomically`
        change(`${action}${compatEntries.length > 0 ? ' with compatibility overrides' : ''}`)
        // Provenance drift is the one trigger here that a plain `add` cannot
        // repair. The `file:` spec string is unchanged by definition — the
        // artifact was rebuilt in place — so pnpm resolves the dependency as
        // already satisfied and leaves the stale deployed tree (hard-linked
        // from an earlier generation) untouched. Evict exactly the drifted
        // overlays first so the add has to materialize them again.
        for (const entry of compatDrifted) {
          const staleDir = path.join(PROFILE_DIR, 'node_modules', ...entry.name.split('/'))
          await rm(staleDir, { recursive: true, force: true })
        }
        // pnpm stages and commits all local specs as one operation. Do not remove
        // the last-known-good owner first: a failed build or add must leave the
        // previous federation + Connection pair intact.
        installed = dshCli(['plugin', '--profile', PROFILE, 'add', ...compatSpecs, spec], { version: manifest.dshVersion })
        if (!installed) fail(`failed to deploy ${name}${compatEntries.length > 0 ? ' and compatibility overrides' : ''}`)
        // Verify the eviction actually took: an add that "succeeds" while the
        // overlay is still stale must not be reported as a repair.
        if (installed && compatDrifted.length > 0) {
          const unresolved = compatDrifted.filter(entry =>
            compatProvenanceOf(readJson(deployedPackageJsonPath(entry.name))) !== compatProvenance[entry.name])
          if (unresolved.length > 0) {
            installed = false
            fail(`compatibility overrides still report a different upstream base after reinstall (${unresolved.map(e => e.name).join(', ')})`)
          }
        }
      }
    } else if (current === undefined) {
      change(`install ${item.source} package ${name} (${spec})`)
      installed = dshCli(['plugin', '--profile', PROFILE, 'add', spec], { version: manifest.dshVersion })
      if (!installed) fail(`failed to install ${name}`)
    } else {
      log(`package ${name}@${current} up-to-date`)
    }
    // Post-install verification for every path above, not just the repair
    // branch: the CLI's exit code reports that the install *ran*, never that
    // the promised files arrived. A first install of an incomplete publish
    // would otherwise be recorded as a success and only surface later as a
    // loader crash. Skipped when the install already failed (that failure is
    // the first cause and is reported on its own).
    if (installed && missingFiles.length === 0) {
      const missingAfterInstall = missingDeployedFiles(name)
      if (missingAfterInstall.length > 0) {
        installed = false
        nextUnrepairable[name] = repairIdentity
        fail(`${name} installed but is missing ${missingAfterInstall.join(', ')}; its source does not satisfy its own manifest`)
      }
    }
    if (installed && localHash !== undefined && buildInputHash !== undefined) {
      nextLocalHashes[name] = localHash
      nextBuildInputs[name] = buildInputHash
      Object.assign(nextCompatHashes, compatHashes)
      nextManagedCompat[name] = compatEntries.map(entry => entry.name)
    }
  }
  state.localPackageHashes = nextLocalHashes
  state.localPackageBuildInputs = nextBuildInputs
  state.localPackageBuiltFrom = nextBuiltFrom
  state.compatDependencyHashes = nextCompatHashes
  state.managedCompatDependencies = nextManagedCompat
  // Rebuilt from scratch each run: a package that no longer reports missing
  // files simply stops being listed, so a fixed upstream self-clears.
  if (Object.keys(nextUnrepairable).length > 0) state.unrepairablePackages = nextUnrepairable
  else delete state.unrepairablePackages
  await saveState(state)

  // normalize bundles: shipped base (non-managed) entries first, then enabled managed in manifest order.
  // Only bundle-declaring packages join the layer stack: a package without a dsh.bundle manifest
  // is a plain dependency (mirrors `dsh plugin add` reconciliation); forcing it into bundles
  // would fail profile load ("bundle without dsh.bundle manifest").
  const refreshed = readJson(profilePkgPath)
  if (refreshed !== undefined) {
    const managed = new Set([...names.values(), ...(state.managedPackages ?? [])])
    const base = (refreshed.dsh?.profile?.bundles ?? []).filter((b) => !managed.has(b))
    const bundleNames = enabledNames.filter((name) => declaresBundle(name))
    const bundles = [...base, ...bundleNames]
    const before = JSON.stringify(refreshed.dsh?.profile?.bundles ?? [])
    refreshed.dsh ??= {}
    refreshed.dsh.profile ??= {}
    refreshed.dsh.profile.bundles = bundles
    if (JSON.stringify(bundles) !== before) {
      change(`bundles: [${bundles.join(', ')}]`)
      await writeJson(profilePkgPath, refreshed)
    }
    if (JSON.stringify(state.shippedBundles ?? []) !== JSON.stringify(base)) {
      state.shippedBundles = base
      await saveState(state)
    }
  }
}

/**
 * One-click reset: remove every plugin beyond the shipped base set, reset the
 * generated patch layer, and drop synced presets/skills. Reversible via sync.
 */
async function doReset(manifest) {
  const state = await loadState()
  const shipped = state.shippedBundles ?? ['@deepseek-ai/dsh-base', '@deepseek-ai/dsh-web-app']
  const profilePkgPath = path.join(PROFILE_DIR, 'package.json')
  const profilePkg = readJson(profilePkgPath)
  if (profilePkg === undefined) return fail(`profile package.json missing at ${PROFILE_DIR}`)

  const bundles = profilePkg.dsh?.profile?.bundles ?? []
  const removable = [...new Set([
    ...bundles.filter((b) => !shipped.includes(b)),
    ...Object.keys(profilePkg.dependencies ?? {}).filter((d) => !shipped.includes(d)),
  ])]
  for (const name of removable) {
    change(`remove plugin ${name}`)
    if (!dshCli(['plugin', '--profile', PROFILE, 'remove', name], { version: manifest.dshVersion })) fail(`failed to remove ${name}`)
  }

  const refreshed = readJson(profilePkgPath) ?? profilePkg
  refreshed.dsh ??= {}
  refreshed.dsh.profile ??= {}
  refreshed.dsh.profile.bundles = shipped
  await writeJson(profilePkgPath, refreshed)

  const target = path.join(PROFILE_DIR, 'cordis.patch.yml')
  const content = GENERATED_HEADER + '\n[]\n'
  if (!existsSync(target) || readFileSync(target, 'utf8') !== content) {
    if (existsSync(target)) await writeFile(target + '.bak', readFileSync(target, 'utf8'))
    change(`reset ${target}`)
    await mkdir(path.dirname(target), { recursive: true })
    await writeFile(target, content)
  }

  for (const key of Object.keys(state)) {
    const m = key.match(/^(preset|skill):(.+)$/)
    if (m === null) continue
    const dst = path.join(DSH_HOME, m[1] === 'preset' ? '.agent-presets' : 'skills', m[2])
    if (existsSync(dst)) {
      change(`remove ${m[1]} ${m[2]}`)
      await rm(dst, { recursive: true, force: true })
    }
    delete state[key]
  }
  delete state.managedPackages
  delete state.localPackageHashes
  delete state.localPackageBuildInputs
  // Reset discards the deployment, so a surviving provenance claim would be
  // evidence about a state that no longer exists.
  delete state.localPackageBuiltFrom
  delete state.compatDependencyHashes
  delete state.managedCompatDependencies
  delete state.managedDependencies
  delete state['managed:preset']
  delete state['managed:skill']
  await saveState(state)
}

async function syncDirs(manifest, items, type, srcDir, dstRoot, requiredFile, label) {
  const state = await loadState()
  const managed = items.filter((i) => i.type === type)
  const enabled = managed.filter((i) => i.enabled)
  for (const item of enabled) {
    const src = sourceDirOf(item, srcDir)
    const dst = path.join(dstRoot, item.id)
    if (!existsSync(path.join(src, requiredFile))) {
      fail(`${label} ${item.id}: ${path.join(src, requiredFile)} missing`)
      continue
    }
    const hash = await dirHash(src)
    if (state[`${type}:${item.id}`] === hash && existsSync(path.join(dst, requiredFile))) {
      log(`${label} ${item.id} up-to-date`)
      continue
    }
    change(`copy ${label} ${item.id} -> ${dst}`)
    await rm(dst, { recursive: true, force: true })
    await mkdir(path.dirname(dst), { recursive: true })
    await cp(src, dst, { recursive: true })
    state[`${type}:${item.id}`] = hash
  }
  for (const item of managed.filter((i) => !i.enabled)) {
    const key = `${type}:${item.id}`
    if (state[key] !== undefined) {
      const dst = path.join(dstRoot, item.id)
      if (existsSync(dst)) {
        change(`remove disabled ${label} ${item.id}`)
        await rm(dst, { recursive: true, force: true })
      }
      delete state[key]
    }
  }
  // remove entries deleted from the manifest (previously managed, now absent)
  const currentIds = new Set(managed.map((i) => i.id))
  for (const id of state[`managed:${type}`] ?? []) {
    if (currentIds.has(id)) continue
    const key = `${type}:${id}`
    if (state[key] !== undefined) {
      const dst = path.join(dstRoot, id)
      if (existsSync(dst)) {
        change(`remove deleted ${label} ${id}`)
        await rm(dst, { recursive: true, force: true })
      }
    }
    delete state[key]
  }
  state[`managed:${type}`] = [...currentIds]
  await saveState(state)
}

async function syncPatches(items, manifest) {
  const fragments = items.filter((i) => i.type === 'patch' && i.enabled)
  const target = path.join(PROFILE_DIR, 'cordis.patch.yml')
  const parts = []
  for (const item of fragments) {
    const file = patchFileOf(item)
    if (!existsSync(file)) {
      fail(`patch ${item.id}: ${file} missing`)
      continue
    }
    parts.push(`# --- fragment: ${item.id} ---\n` + readFileSync(file, 'utf8').trimEnd() + '\n')
  }
  const body = parts.length === 0 ? '[]\n' : parts.join('\n')
  const content = GENERATED_HEADER + '\n' + body
  const existing = existsSync(target) ? readFileSync(target, 'utf8') : ''
  if (existing === content) {
    log('patches up-to-date')
    return
  }
  change(`generate ${target}`)
  if (existing !== '') await writeFile(target + '.bak', existing)
  await mkdir(path.dirname(target), { recursive: true })
  await writeFile(target, content)
}

function logVersion(manifest) {
  log(`dshVersion: ${manifest.dshVersion} (launcher bin/dsh reads dsh.yaml as the single source)`)
}

// ---------- main ----------
async function main() {
  const manifest = loadManifest()
  if (process.argv.includes('--reset')) {
    // reset 只依据状态账本撤销受管部署,不预检源码:源码缺失不应阻止撤销。
    await mkdir(PROFILE_DIR, { recursive: true })
    await migrateLegacyState()
    await ensureProfileScaffold(manifest)
    await doReset(manifest)
    await syncAgentInstructions(manifest.agentInstructions, { reset: true })
  } else {
    // 预检全部在任何 $DSH_HOME 写入之前(design D7)。
    preflightSources(manifest.items, manifest.hostRuntime)
    const packageNames = resolvePackageNames(manifest.items, manifest.deps)
    await mkdir(PROFILE_DIR, { recursive: true })
    // 全新机器上 profile 骨架尚不存在;package 物化以它为前置。
    await ensureProfileScaffold(manifest)
    // scope 预检依赖 profile .npmrc,故排在骨架之后、任何定制物化与账本迁移之前。
    preflightScopes(manifest.items)
    await migrateLegacyState()
    await syncAgentInstructions(manifest.agentInstructions)
    await syncDependencies(manifest)
    await syncPackages(manifest, manifest.items, packageNames)
    await syncDirs(manifest, manifest.items, 'preset', 'presets', path.join(DSH_HOME, '.agent-presets'), 'agent.cordis.yml', 'preset')
    await syncDirs(manifest, manifest.items, 'skill', 'skills', path.join(DSH_HOME, 'skills'), 'SKILL.md', 'skill')
    await syncPatches(manifest.items, manifest)
  }
  logVersion(manifest)
  console.log('')
  if (failures.length > 0) {
    console.error(`[sync] finished with ${failures.length} failure(s):`)
    for (const f of failures) console.error(`  - ${f}`)
    process.exitCode = 1
    return
  }
  if (changes.length === 0) log('no changes — deployment already matches manifest')
  else log(`done — ${changes.length} change(s) applied`)
}

main().catch((error) => {
  console.error(`[sync] ERROR ${String(error?.message ?? error)}`)
  process.exitCode = 1
})
