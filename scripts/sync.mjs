#!/usr/bin/env node
// ohmydsh sync — materialize dsh.yaml customizations into ~/.dsh.
// Idempotent; the repository (dsh.yaml + customization dirs) is the source of truth.
import { readFile, writeFile, mkdir, cp, rm, readdir, stat, rename, realpath } from 'node:fs/promises'
import { existsSync, readFileSync, realpathSync, statSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { spawnSync } from 'node:child_process'
import path from 'node:path'
import os from 'node:os'
import { fileURLToPath } from 'node:url'
import yaml from 'js-yaml'
import { runDshCli } from './lib/dsh-cli.mjs'
import { assertHostRuntimeSources, declaredHostRuntimeFromManifest } from './lib/dsh-host-runtime.mjs'
import { assertNoReservedEntryKeys, loadOverlayCustomizations, mergeOverlayCustomizations } from './lib/manifest-overlay.mjs'

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const DSH_HOME = resolveDshHome(process.env.DSH_HOME)
const PROFILE = process.env.DSH_PROFILE ?? 'web'
const PROFILE_DIR = path.join(DSH_HOME, 'profiles', PROFILE)
// Deployment bookkeeping. The filename is deliberately independent of the
// repository name: it used to carry it (.zydsh- / .mydsh- / .ohmydsh-), so every
// repo rename orphaned the state and sync restarted with an empty ledger —
// silently re-adopting most artifacts, but hard-failing on the fail-closed
// AGENTS.md path. Legacy names are migrated on startup, newest generation first.
const STATE_FILE = path.join(DSH_HOME, '.dsh-sync-state.json')
const LEGACY_STATE_FILES = ['.ohmydsh-sync-state.json', '.mydsh-sync-state.json', '.zydsh-sync-state.json']
const GENERATED_HEADER = `# GENERATED by ohmydsh scripts/sync.mjs — do not edit by hand.\n# Source of truth: ${REPO}/dsh.yaml (plus the local manifest overlay, if any). Edit there, then re-run sync.\n`

/**
 * Truthy/falsy spellings accepted for a boolean env override. Shared by the
 * per-customization `enabledEnv` field, so every mechanism carries the same
 * meaning for the same spellings.
 */
const ENV_BOOL_TRUE = new Set(['1', 'true', 'yes', 'on'])
const ENV_BOOL_FALSE = new Set(['0', 'false', 'no', 'off'])

/**
 * Resolve a boolean env override: unset/blank/unrecognized returns undefined
 * so the caller falls back to its manifest-declared default; a recognized
 * truthy/falsy spelling (case-insensitive) returns true/false. Used by the
 * per-customization `enabledEnv` field (loadManifest).
 */
function resolveEnabledOverride(raw) {
  if (raw === undefined) return undefined
  const v = raw.trim().toLowerCase()
  if (v === '') return undefined
  if (ENV_BOOL_TRUE.has(v)) return true
  if (ENV_BOOL_FALSE.has(v)) return false
  return undefined
}

const failures = []
const changes = []
const log = (msg) => console.log(`[sync] ${msg}`)
const change = (msg) => { changes.push(msg); log(msg) }
const fail = (msg) => { failures.push(msg); console.error(`[sync] ERROR ${msg}`) }

// ---------- manifest ----------
function loadManifest() {
  const file = path.join(REPO, 'dsh.yaml')
  if (!existsSync(file)) {
    throw new Error(`manifest missing: ${file} — create it first (see README.md)`)
  }
  const doc = yaml.load(readFileSync(file, 'utf8'))
  if (typeof doc !== 'object' || doc === null) throw new Error(`manifest ${file} is empty or not a YAML mapping`)
  if (typeof doc.dshVersion !== 'string' || doc.dshVersion === '') throw new Error('manifest: dshVersion is required')
  if (!Array.isArray(doc.customizations)) throw new Error('manifest: customizations must be a list')
  // Append the local overlay's customizations *before* the Host runtime fence
  // and before per-entry normalization. Both are load-bearing:
  //   - declaredHostRuntimeFromManifest() receives the whole doc and asserts
  //     "at most one owner of hostRuntimeCompatibility". Merging after it would
  //     let an overlay entry bypass the version fence outright and would break
  //     that invariant silently (one public + one overlay = two real owners).
  //   - Merging into `doc` rather than into the normalized `items` means overlay
  //     entries traverse the exact same validation chain below, so no consumer
  //     needs a per-source branch and no check can be accidentally skipped.
  // Public entries are checked before their owning root is attached, overlay
  // entries inside the overlay loader: neither file may choose its own root.
  doc.customizations.forEach((item, index) => assertNoReservedEntryKeys(item, `customizations[${index}] (${item?.id})`))
  doc.customizations = doc.customizations.map((item) =>
    item !== null && typeof item === 'object' && !Array.isArray(item) ? { ...item, sourceRoot: REPO } : item)
  const overlay = loadOverlayCustomizations({ repo: REPO, env: process.env, strict: true })
  mergeOverlayCustomizations(doc, overlay.customizations, overlay.file)
  // Version-fence the reviewed Host overlay before even normalizing the rest of
  // the manifest. loadManifest itself is side-effect free, and main performs no
  // profile/state operation until this entire validation returns.
  const hostRuntime = declaredHostRuntimeFromManifest(doc, { repo: REPO, env: process.env })

  // top-level dependencies: bundle-less support packages (exact-version npm specs)
  const deps = (doc.dependencies ?? []).map((spec, index) => {
    const label = `dependencies[${index}]`
    if (typeof spec !== 'string') throw new Error(`${label}: must be a string npm spec with exact version`)
    const parsed = parseSpec(spec)
    if (parsed === undefined) throw new Error(`${label}: "${spec}" — expected "<name>@<version>"`)
    return { ...parsed, spec }
  })
  const depNames = new Set(deps.map((d) => d.name))

  const items = doc.customizations.map((item, index) => {
    // Overlay entries are appended, so their merged index is meaningless to a
    // reader: "customizations[30]" would send them hunting for a 30th entry the
    // public manifest does not have. Name the overlay instead.
    const label = item?.overlaySource === undefined
      ? `customizations[${index}]`
      : `local manifest overlay ${item.overlaySource} entry`
    if (typeof item.id !== 'string' || !/^[a-z0-9][a-z0-9._-]*$/i.test(item.id)) throw new Error(`${label}: valid string id required`)
    if (!['package', 'preset', 'patch', 'skill'].includes(item.type)) throw new Error(`${label} (${item.id}): type must be package|preset|patch|skill`)
    const source = item.source ?? 'local'
    if (!['local', 'remote'].includes(source)) throw new Error(`${label} (${item.id}): source must be local|remote`)
    if (source === 'remote' && item.type !== 'package') throw new Error(`${label} (${item.id}): source remote only applies to type package`)
    if (item.type === 'package' && source === 'remote' && typeof item.spec !== 'string') throw new Error(`${label} (${item.id}): remote package requires spec`)
    if (item.name !== undefined && (typeof item.name !== 'string' || !/^(@[^/@]+\/[^/@]+|[^/@]+)$/.test(item.name))) throw new Error(`${label} (${item.id}): name must be a valid npm package name`)
    // npmNameOf trusts `name` first while the install uses `spec`: letting them
    // disagree would let a fake name slip past the package-name uniqueness check.
    if (item.type === 'package' && source === 'remote' && item.name !== undefined && parseSpec(item.spec) !== undefined && parseSpec(item.spec).name !== item.name) {
      throw new Error(`${label} (${item.id}): name "${item.name}" does not match the package name "${parseSpec(item.spec).name}" of spec ${item.spec}`)
    }
    if (item.type === 'package' && source === 'remote' && parseSpec(item.spec) === undefined && item.name === undefined) throw new Error(`${label} (${item.id}): remote package with a non-npm spec requires an explicit name (real npm package name)`)
    // npmScopes: scopes whose registry must already be configured for the
    // install to work. Checked, never written (design D4).
    let npmScopes
    if (item.npmScopes !== undefined) {
      if (item.type !== 'package') throw new Error(`${label} (${item.id}): npmScopes is only valid on type package`)
      if (!Array.isArray(item.npmScopes) || item.npmScopes.some((scope) => typeof scope !== 'string' || !/^@[a-z0-9][a-z0-9._-]*$/.test(scope))) {
        throw new Error(`${label} (${item.id}): npmScopes must be a list of npm scope names like "@example"`)
      }
      npmScopes = [...new Set(item.npmScopes)]
    }
    if ((item.type === 'package' || item.type === 'preset') && typeof item.version !== 'string') throw new Error(`${label} (${item.id}): package/preset requires version`)
    // deps: ownership references into the top-level dependencies list (not an install source)
    if (item.deps !== undefined) {
      if (!Array.isArray(item.deps) || item.deps.some((d) => typeof d !== 'string')) throw new Error(`${label} (${item.id}): deps must be a list of package names`)
      for (const name of item.deps) {
        if (!depNames.has(name)) throw new Error(`${label} (${item.id}): deps references "${name}" which is missing from top-level dependencies`)
      }
    }
    // A local bundle may build a fixed-source compatibility package that must
    // resolve under an existing official package identity. It is installed in
    // the same pnpm transaction as its owner and removed with that owner.
    let buildInputs
    if (item.buildInputs !== undefined) {
      if (source !== 'local' || !Array.isArray(item.buildInputs) || item.buildInputs.some(entry => typeof entry !== 'string' || entry === '' || path.isAbsolute(entry))) {
        throw new Error(`${label} (${item.id}): buildInputs must be relative paths (under the entry's source root) on a local customization`)
      }
      buildInputs = item.buildInputs.map((entry, inputIndex) => {
        const normalized = path.normalize(entry)
        if (normalized === '..' || normalized.startsWith(`..${path.sep}`)) throw new Error(`${label} (${item.id}).buildInputs[${inputIndex}]: path must stay inside the entry's source root ${item.sourceRoot ?? REPO}`)
        return normalized
      })
    }
    let compatDependencies
    if (item.compatDependencies !== undefined) {
      if (item.type !== 'package' || source !== 'local' || !Array.isArray(item.compatDependencies)) {
        throw new Error(`${label} (${item.id}): compatDependencies is only valid as a list on local packages`)
      }
      compatDependencies = item.compatDependencies.map((entry, compatIndex) => {
        const compatLabel = `${label} (${item.id}).compatDependencies[${compatIndex}]`
        if (typeof entry !== 'object' || entry === null || Array.isArray(entry)) throw new Error(`${compatLabel}: mapping required`)
        if (typeof entry.name !== 'string' || !/^(@[^/@]+\/[^/@]+|[^/@]+)$/.test(entry.name)) throw new Error(`${compatLabel}: valid npm package name required`)
        if (typeof entry.path !== 'string' || entry.path === '' || path.isAbsolute(entry.path)) throw new Error(`${compatLabel}: path must be a non-empty relative path`)
        const normalized = path.normalize(entry.path)
        if (normalized === '..' || normalized.startsWith(`..${path.sep}`)) throw new Error(`${compatLabel}: path must stay inside the owner package`)
        if (depNames.has(entry.name)) throw new Error(`${compatLabel}: conflicts with top-level dependency ${entry.name}`)
        return { name: entry.name, path: normalized }
      })
    }
    // enabledEnv: optional per-customization env override of `enabled`,
    // machine-specific opt-in without touching dsh.yaml.
    // Validated eagerly (fail closed) so a typo'd env name doesn't silently
    // degrade into "the switch never seems to work" with no diagnostic.
    let enabled = item.enabled !== false
    if (item.enabledEnv !== undefined) {
      if (typeof item.enabledEnv !== 'string' || !/^DSH_[A-Z0-9_]+$/.test(item.enabledEnv)) {
        throw new Error(`${label} (${item.id}): enabledEnv must be an uppercase DSH_-prefixed env var name (e.g. DSH_${item.id.toUpperCase().replace(/[^A-Z0-9]+/g, '_')})`)
      }
      const override = resolveEnabledOverride(process.env[item.enabledEnv])
      if (override !== undefined) enabled = override
    }
    return { ...item, source, enabled, buildInputs, compatDependencies, npmScopes }
  })
  const web = doc.web ?? {}
  if (typeof web !== 'object' || web === null || Array.isArray(web)) {
    throw new Error('manifest: web must be a mapping (web.open: true|false)')
  }
  if (web.open !== undefined && typeof web.open !== 'boolean') {
    throw new Error('manifest: web.open must be a boolean')
  }
  const agentInstructions = validateAgentInstructions(doc.agentInstructions)
  return { dshVersion: doc.dshVersion, items, deps, agentInstructions, hostRuntime, web: { open: web.open !== false } }
}

function validateAgentInstructions(value) {
  if (value === undefined) return undefined
  if (typeof value !== 'object' || value === null || Array.isArray(value)) {
    throw new Error('manifest: agentInstructions must be a mapping with enabled and source')
  }
  if (typeof value.enabled !== 'boolean') throw new Error('manifest: agentInstructions.enabled must be a boolean')
  if (typeof value.source !== 'string' || value.source.trim() === '') {
    throw new Error('manifest: agentInstructions.source must be a non-empty repository-relative path')
  }
  const source = value.source.trim()
  if (path.isAbsolute(source)) throw new Error('manifest: agentInstructions.source must be a repository-relative path, not an absolute path')
  const sourcePath = path.resolve(REPO, source)
  const relative = path.relative(REPO, sourcePath)
  if (relative === '..' || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative)) {
    throw new Error('manifest: agentInstructions.source must not escape the repository')
  }
  return { enabled: value.enabled, source: relative.split(path.sep).join('/'), sourcePath }
}

function parseSpec(spec) {
  const m = String(spec).match(/^(@[^/@]+\/[^/@]+|[^/@]+)@(.+)$/)
  if (m === null || m[2] === '') return undefined
  return { name: m[1], version: m[2] }
}

// ---------- helpers ----------
function resolveDshHome(value) {
  const configured = typeof value === 'string' ? value.trim() : ''
  if (configured === '') return path.join(os.homedir(), '.dsh')
  if (configured === '~') return os.homedir()
  if (configured.startsWith(`~${path.sep}`) || configured.startsWith('~/')) {
    return path.resolve(os.homedir(), configured.slice(2))
  }
  return path.resolve(configured)
}

function readJson(file) {
  try { return JSON.parse(readFileSync(file, 'utf8')) } catch { return undefined }
}

async function writeJson(file, value) {
  await writeFile(file, JSON.stringify(value, null, 2) + '\n')
}

function contentHash(content) {
  return createHash('sha256').update(content).digest('hex')
}

async function atomicWrite(file, content) {
  await mkdir(path.dirname(file), { recursive: true })
  const temp = path.join(path.dirname(file), `.${path.basename(file)}.tmp-${process.pid}-${Date.now()}`)
  try {
    await writeFile(temp, content, { flag: 'wx' })
    await rename(temp, file)
  } finally {
    await rm(temp, { force: true })
  }
}

async function filesHash(dir, options = {}) {
  const entries = await collectFiles(dir, dir, options)
  const h = createHash('sha256')
  for (const rel of entries.sort()) {
    h.update(rel + '\0')
    h.update(await readFile(path.join(dir, rel)))
  }
  return h.digest('hex')
}

async function dirHash(dir) {
  return filesHash(dir)
}

async function collectFiles(dir, base = dir, options = {}) {
  const out = []
  const excludeDirs = new Set(options.excludeDirs ?? [])
  const excludeFiles = new Set(options.excludeFiles ?? [])
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const rel = path.relative(base, path.join(dir, entry.name)).split(path.sep).join('/')
    if (entry.name.startsWith('.') || entry.name === 'node_modules') continue
    if (entry.isDirectory() && excludeDirs.has(rel)) continue
    if (entry.isFile() && (excludeFiles.has(entry.name) || excludeFiles.has(rel))) continue
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) out.push(...await collectFiles(full, base, options))
    else if (entry.isFile()) out.push(path.relative(base, full))
  }
  return out
}

async function localBuildInputHash(dir, extraInputs = [], root = REPO) {
  const entries = await collectFiles(dir, dir, {
    excludeDirs: ['lib', 'node_modules', 'test', 'tests', 'checking', 'coverage'],
    excludeFiles: ['package-lock.json', 'npm-debug.log'],
  })
  const selected = entries.filter((rel) => {
    const normalized = rel.split(path.sep).join('/')
    const base = path.posix.basename(normalized)
    return normalized.startsWith('src/') ||
      normalized === 'package.json' ||
      (!normalized.includes('/') && /\.mjs$/.test(normalized)) ||
      /^tsconfig(?:\..+)?\.json$/.test(base) ||
      /^(?:tsdown|vite|rollup|esbuild)\.config\.[cm]?[jt]s$/.test(base)
  })
  const h = createHash('sha256')
  h.update(`node:${process.version}\0`)
  for (const rel of selected.sort()) {
    h.update(rel + '\0')
    h.update(await readFile(path.join(dir, rel)))
  }
  for (const input of [...extraInputs].sort()) {
    const absolute = path.join(root, input)
    const inputStat = await stat(absolute).catch(() => undefined)
    if (inputStat === undefined || !inputStat.isFile()) throw new Error(`local build input missing or not a regular file: ${input}`)
    h.update(`repo:${input}\0`)
    h.update(await readFile(absolute))
  }
  return h.digest('hex')
}

async function installContentHashOf(dir, pkg) {
  const included = new Set(['package.json', pkg?.dsh?.bundle?.patch, ...(pkg?.files ?? [])].filter(Boolean))
  const entries = await collectFiles(dir, dir, {
    excludeDirs: Array.isArray(pkg?.files) && pkg.files.length > 0
      ? ['node_modules', 'src', 'test', 'tests', 'checking', 'coverage']
      : ['node_modules', 'test', 'tests', 'checking', 'coverage'],
    excludeFiles: ['package-lock.json', 'tsconfig.json', 'tsconfig.client.json', 'tsdown.config.ts', 'vitest.config.ts'],
  })
  const selected = Array.isArray(pkg?.files) && pkg.files.length > 0
    ? entries.filter((rel) => {
        const normalized = rel.split(path.sep).join('/')
        return [...included].some((item) => normalized === item || normalized.startsWith(`${item}/`))
      })
    : entries
  const h = createHash('sha256')
  for (const rel of selected.sort()) {
    h.update(rel + '\0')
    h.update(await readFile(path.join(dir, rel)))
  }
  return h.digest('hex')
}

async function localInstallContentHash(dir) {
  const pkg = readJson(path.join(dir, 'package.json'))
  return installContentHashOf(dir, pkg)
}

/**
 * Content hash of a deployed local package, using the SOURCE manifest's
 * publishable-set contract (the deployed package.json may have been
 * rewritten by pnpm). The deployment directory must exist; absence is
 * reported as null (the missing-files repair path owns directory creation).
 */
async function deployedContentHash(sourcePkg, name) {
  const deployedDir = path.join(PROFILE_DIR, 'node_modules', ...name.split('/'))
  if (!existsSync(deployedDir)) return null
  return installContentHashOf(deployedDir, sourcePkg)
}

/**
 * Force-refresh a deployed local package. pnpm treats `file:` directory
 * dependencies as merge-without-overwrite: a plain re-add keeps every
 * already-present subtree file (lib/*) stale. Evicting the deployed copy
 * first forces fresh materialization. Atomic: on failure (or when the
 * re-verified bytes still mismatch the source) the previous deployment is
 * restored and false is returned — never a half-deployed state.
 */
async function refreshLocalDeployment(localDir, name, spec, compatSpecs, expectedHash, dshVersion) {
  const deployedDir = path.join(PROFILE_DIR, 'node_modules', ...name.split('/'))
  const quarantine = `${deployedDir}.ohmydsh-refresh`
  const sourcePkg = readJson(path.join(localDir, 'package.json'))
  await rm(quarantine, { recursive: true, force: true })
  await rename(deployedDir, quarantine).catch(() => {})
  const installed = dshCli(['plugin', '--profile', PROFILE, 'add', ...compatSpecs, spec], { version: dshVersion })
  if (!installed) {
    // add failed: restore the previous deployment (nothing else was touched).
    if (!existsSync(deployedDir) && existsSync(quarantine)) {
      await rename(quarantine, deployedDir).catch(() => {})
      log(`restored previous deployment of ${name} after failed refresh`)
    }
    return false
  }
  const deployedHash = await deployedContentHash(sourcePkg, name)
  if (deployedHash === null || deployedHash !== expectedHash) {
    // add "succeeded" but the deployed bytes still do not match the source
    // (e.g. pnpm merging from a cached/stale pack): restore, never accept.
    await rm(deployedDir, { recursive: true, force: true })
    if (existsSync(quarantine)) {
      await rename(quarantine, deployedDir).catch(() => {})
      log(`restored previous deployment of ${name} after refresh verification mismatch`)
    }
    return false
  }
  await rm(quarantine, { recursive: true, force: true })
  return true
}

function localBuildOutputsExist(dir, pkg) {
  if (typeof pkg?.scripts?.build !== 'string') return true
  const files = Array.isArray(pkg.files) ? pkg.files : []
  const outputRoots = files.filter((entry) => typeof entry === 'string' && entry !== '')
  if (outputRoots.length === 0) return existsSync(path.join(dir, 'lib'))
  return outputRoots.every((entry) => existsSync(path.join(dir, entry)))
}

function runLocalBuild(item, dir) {
  const pkg = readJson(path.join(dir, 'package.json'))
  if (typeof pkg?.scripts?.build !== 'string') return true
  change(`build local package ${pkg.name ?? item.id}`)
  // Each root is its own npm workspace project with its own lockfile, so the
  // build runs where the package lives (design D3).
  const root = item.sourceRoot ?? REPO
  const result = spawnSync('npm', ['run', 'build', '--workspace', pkg.name], {
    cwd: root,
    stdio: 'inherit',
  })
  if (result.status === 0) return true
  fail(`local package ${pkg.name ?? item.id}: npm run build --workspace ${pkg.name} (in ${root}) failed before deployment`)
  return false
}

/**
 * Adopt the state written under a previous repository name. Runs before any
 * state read: renaming (not copying) the newest legacy ledger keeps ownership
 * of already-deployed artifacts across a repo rename. Older generations are
 * left in place and only reported — this function never deletes.
 */
async function migrateLegacyState() {
  if (existsSync(STATE_FILE)) return
  const present = LEGACY_STATE_FILES.map(name => path.join(DSH_HOME, name)).filter(existsSync)
  if (present.length === 0) return
  const [newest, ...older] = present
  await mkdir(path.dirname(STATE_FILE), { recursive: true })
  await rename(newest, STATE_FILE)
  change(`migrate sync state ${path.basename(newest)} -> ${path.basename(STATE_FILE)}`)
  for (const stale of older) log(`ignoring superseded sync state ${path.basename(stale)} (safe to delete)`)
}

async function loadState() {
  return readJson(STATE_FILE) ?? {}
}

async function saveState(state) {
  await mkdir(path.dirname(STATE_FILE), { recursive: true })
  await atomicWrite(STATE_FILE, JSON.stringify(state, null, 2) + '\n')
}

function dshCli(args, opts = {}) {
  // 升级链可靠性(see openspec/changes/upgrade-cli-provisioning):解析目标
  // 版本 CLI 的就绪 bin 并 node 直连执行,首次就绪后不再发起新的 npx
  // 进程,避免 libnpmexec 安装锁竞争(ECOMPROMISED)。DSH_BIN 优先保留。
  return runDshCli(args, {
    spec: `@deepseek-ai/dsh@${opts.version}`,
    version: opts.version,
    dshBinEnv: process.env.DSH_BIN,
    stdio: opts.stdio,
  })
}

/**
 * 全新 `$DSH_HOME` 的 profile 骨架物化。
 *
 * 症状:在没有 `~/.dsh` 的机器上首次 `dsh build`,syncPackages/doReset 读不到
 * `profiles/<name>/package.json` 就 fail(`profile package.json missing`),
 * 于是全部 package 定制被跳过、启动缺插件 —— sync 假定 profile 已由此前某次
 * DSH 运行初始化过,但全新机器上并没有这一前置。
 *
 * 修法:把这一前置变成 sync 自己的显式步骤,而不是复制一份 profile 模板。
 * 骨架的真相源是运行体自身(`@deepseek-ai/dsh-app-boot` 的 PROFILE_TEMPLATES /
 * initProfile:manifest + cordis.patch.yml + pnpm-workspace.yaml)。这里以
 * `--profile <name> --dump-default-config` 调用目标版本 CLI,只取其"加载
 * profile 时按需 initProfile"的副作用(不读 user layer,故不会被后续生成的
 * patch 层内容影响),输出丢弃。
 *
 * 语义:
 * - 幂等 —— manifest 已存在直接返回,不触碰任何既有文件(initProfile 本身也
 *   从不覆盖已存在的文件);
 * - fail closed —— 骨架无法物化时报错,让调用方看到真正的首因,而不是随后
 *   一连串"package 装不上"的次生失败。
 * @returns {Promise<boolean>} profile manifest 是否已就绪。
 */
async function ensureProfileScaffold(manifest) {
  const profilePkgPath = path.join(PROFILE_DIR, 'package.json')
  if (existsSync(profilePkgPath)) return true
  change(`initialize profile ${PROFILE} at ${PROFILE_DIR}`)
  await mkdir(PROFILE_DIR, { recursive: true })
  // 副作用调用:输出是整棵默认配置树,对 sync 日志无意义,丢弃。
  dshCli(['--profile', PROFILE, '--dump-default-config'], { version: manifest.dshVersion, stdio: 'ignore' })
  if (existsSync(profilePkgPath)) return true
  fail(`failed to initialize profile ${PROFILE} at ${PROFILE_DIR} (dsh ${manifest.dshVersion} could not create its profile manifest)`)
  return false
}

/**
 * Directory a local customization's sources live in: `<owning root>/<dir>/<id>`.
 * The owning root is the public repo for public entries and the overlay root
 * for overlay entries; it is derived by the loaders, never by the entry.
 */
function sourceDirOf(item, dir) {
  return path.join(item.sourceRoot ?? REPO, dir, item.id)
}

/**
 * Is `target` inside `root` once both are resolved through symlinks?
 * Same comparison as syncAgentInstructions' containment check.
 */
function realpathInside(target, root) {
  const relative = path.relative(realpathSync(root), realpathSync(target))
  return !(relative === '..' || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative))
}

/**
 * The source paths an enabled customization needs, each with the kind it must
 * be. Mirrors what the materializers read: package.json (+ compat artifacts +
 * extra build inputs) for local packages, the required file of a preset/skill
 * directory, the fragment of a patch.
 */
function requiredSourcesOf(item) {
  const root = item.sourceRoot ?? REPO
  switch (item.type) {
    case 'package': {
      if (item.source !== 'local') return []
      const dir = sourceDirOf(item, 'packages')
      return [
        { path: dir, kind: 'dir' },
        { path: path.join(dir, 'package.json'), kind: 'file' },
        ...(item.compatDependencies ?? []).flatMap((entry) => [
          { path: path.join(dir, entry.path), kind: 'dir' },
          { path: path.join(dir, entry.path, 'package.json'), kind: 'file' },
        ]),
        ...(item.buildInputs ?? []).map((input) => ({ path: path.join(root, input), kind: 'file' })),
      ]
    }
    case 'preset': {
      const dir = sourceDirOf(item, 'presets')
      return [{ path: dir, kind: 'dir' }, { path: path.join(dir, 'agent.cordis.yml'), kind: 'file' }]
    }
    case 'skill': {
      const dir = sourceDirOf(item, 'skills')
      return [{ path: dir, kind: 'dir' }, { path: path.join(dir, 'SKILL.md'), kind: 'file' }]
    }
    case 'patch':
      return [{ path: patchFileOf(item), kind: 'file' }]
    default:
      return []
  }
}

/**
 * Prove every enabled entry's sources exist and stay inside the entry's owning
 * root before sync writes anything under $DSH_HOME (design D7). All problems
 * are collected and reported together; the materializers keep their own
 * existence checks as a TOCTOU backstop.
 */
function preflightSources(items, hostRuntime = null) {
  const errors = []
  try {
    assertHostRuntimeSources(hostRuntime)
  } catch (error) {
    errors.push(String(error?.message ?? error))
  }
  for (const item of items) {
    if (!item.enabled) continue
    const root = item.sourceRoot ?? REPO
    for (const source of requiredSourcesOf(item)) {
      let info
      try {
        info = statSync(source.path)
      } catch {
        errors.push(`${item.type} ${item.id}: ${source.path} missing`)
        continue
      }
      if (source.kind === 'file' ? !info.isFile() : !info.isDirectory()) {
        errors.push(`${item.type} ${item.id}: ${source.path} must be a ${source.kind === 'file' ? 'regular file' : 'directory'}`)
        continue
      }
      if (!realpathInside(source.path, root)) {
        errors.push(`${item.type} ${item.id}: ${source.path} resolves outside its source root ${root}`)
      }
    }
  }
  if (errors.length > 0) {
    throw new Error(`source preflight failed — nothing was changed:\n  - ${errors.join('\n  - ')}`)
  }
}

/**
 * Resolve every package entry's npm name after source preflight and before any
 * $DSH_HOME write (design D5 step 2). Enabled local sources were proven by the
 * preflight; a disabled local entry is not, so:
 *   - its package.json missing  -> skipped: it then counts as "not in the
 *     manifest" and syncPackages removes it through the managedPackages ledger;
 *   - its package.json present  -> containment-proven before it is read.
 *
 * @returns {Map<string, string>} customization id -> npm package name
 */
function resolvePackageNames(items, deps = []) {
  const names = new Map()
  const errors = []
  for (const item of items) {
    if (item.type !== 'package') continue
    if (item.source === 'local' && !item.enabled) {
      const file = path.join(sourceDirOf(item, 'packages'), 'package.json')
      if (!existsSync(file)) continue
      if (!realpathInside(file, item.sourceRoot ?? REPO)) {
        errors.push(`package ${item.id}: ${file} resolves outside its source root ${item.sourceRoot ?? REPO}`)
        continue
      }
    }
    try {
      names.set(item.id, npmNameOf(item))
    } catch (error) {
      errors.push(String(error?.message ?? error))
    }
  }
  // Uniqueness over the one key space these all share: the profile
  // package.json `dependencies`. Disabled entries count too — "remove disabled
  // package N" would otherwise fight an enabled entry installing N.
  const owners = new Map()
  const claim = (name, owner) => owners.set(name, [...(owners.get(name) ?? []), owner])
  for (const dep of deps) claim(dep.name, 'dependencies')
  for (const item of items) {
    if (item.type !== 'package') continue
    const name = names.get(item.id)
    if (name !== undefined) claim(name, `package ${item.id}`)
    for (const entry of item.compatDependencies ?? []) claim(entry.name, `package ${item.id} compatDependencies`)
  }
  for (const [name, claimants] of owners) {
    if (claimants.length > 1) errors.push(`npm package name ${name} is claimed more than once: ${claimants.join(', ')}`)
  }
  if (errors.length > 0) {
    throw new Error(`package name resolution failed — nothing was changed:\n  - ${errors.join('\n  - ')}`)
  }
  return names
}

/**
 * Every scope an enabled entry declares must resolve to a registry the way npm
 * itself resolves it for an install run from the profile dir: user ~/.npmrc,
 * the profile .npmrc and npm_config_* env all count (design D4). Runs after the
 * profile scaffold exists (the profile .npmrc lives there) and before anything
 * else touches $DSH_HOME, including the legacy ledger migration.
 */
function preflightScopes(items) {
  const declaredBy = new Map()
  for (const item of items) {
    if (!item.enabled) continue
    for (const scope of item.npmScopes ?? []) declaredBy.set(scope, [...(declaredBy.get(scope) ?? []), item.id])
  }
  const errors = []
  for (const [scope, ids] of declaredBy) {
    const result = spawnSync('npm', ['config', 'get', `${scope}:registry`], { cwd: PROFILE_DIR, encoding: 'utf8' })
    const value = String(result.stdout ?? '').trim()
    if (result.status !== 0 || value === '' || value === 'undefined') {
      errors.push(`npm scope ${scope} (required by ${ids.map((id) => `package ${id}`).join(', ')}) has no registry configured for profile ${PROFILE_DIR}; add "${scope}:registry=<url>" to ${path.join(PROFILE_DIR, '.npmrc')} or your user .npmrc`)
    }
  }
  if (errors.length > 0) {
    throw new Error(`npm scope preflight failed — no customization was changed:\n  - ${errors.join('\n  - ')}`)
  }
}

/** A patch customization's fragment file under its owning root. */
function patchFileOf(item) {
  return path.join(item.sourceRoot ?? REPO, 'patches', `${item.id}.yml`)
}

function npmNameOf(item) {
  if (item.source === 'local') {
    const file = path.join(sourceDirOf(item, 'packages'), 'package.json')
    const pkg = readJson(file)
    if (pkg === undefined) throw new Error(`package ${item.id}: ${file} missing`)
    return pkg.name
  }
  if (item.name !== undefined) return item.name
  return parseSpec(item.spec).name
}

function installedVersion(name) {
  const pkg = readJson(path.join(PROFILE_DIR, 'node_modules', ...name.split('/'), 'package.json'))
  return pkg?.version
}

/**
 * Every runtime file a package manifest promises, as package-relative paths.
 *
 * Derived from what the loader actually resolves: `main`, the `exports` tree
 * (any nesting of condition maps / fallback arrays), and `dsh.bundle.patch`
 * (the composition patch the profile reads). Type declarations are excluded:
 * a missing `.d.ts` never breaks a running import, so demanding it would turn
 * a cosmetic gap into a redeploy.
 *
 * Conservative by construction — it must never invent a requirement:
 * - only literal relative specifiers ('./…') are collected; bare specifiers
 *   and URLs address other packages, not files here;
 * - wildcard subpaths ('./*') expand per-request and cannot be checked as a
 *   literal path, so they are skipped;
 * - `null` targets are exports *blocks*, not files;
 * - `types` / `typings` conditions are dropped (see above);
 * - a fallback *array* means "first one that resolves wins", so requiring
 *   every member would flag a healthy package; it contributes nothing;
 * - a condition map is resolved **first-match against the conditions this
 *   loader actually uses**, exactly as Node does — never unioned. Unioning
 *   would demand the `require` branch of an ESM-only package that merely
 *   declares one, condemning healthy packages (`@standard-schema/spec`,
 *   `@upsetjs/venn.js` in this very profile).
 * Anything unrecognized is ignored rather than guessed at.
 * @returns {string[]} unique package-relative paths that must exist on disk.
 */
/** Import conditions the host loader offers, in Node's resolution order. */
const RUNTIME_CONDITIONS = ['node', 'import', 'module-sync', 'default']

function declaredRuntimeFiles(pkg) {
  const found = new Set()
  const addTarget = (value) => {
    if (typeof value !== 'string') return
    if (!value.startsWith('./')) return          // bare specifier / URL: not our file
    if (value.includes('*')) return              // pattern subpath: no single literal path
    if (value.endsWith('/')) return              // directory target: not a single file
    found.add(value.replace(/^\.\//, ''))
  }
  // exports values nest arbitrarily: string | null | array of fallbacks | condition map.
  const walkExports = (node) => {
    if (node === null || node === undefined) return
    if (typeof node === 'string') return addTarget(node)
    if (Array.isArray(node)) return            // fallback list: no single member is required
    if (typeof node !== 'object') return
    // First match wins, mirroring Node — stop at the first condition this
    // runtime would select rather than requiring every branch.
    for (const condition of RUNTIME_CONDITIONS) {
      if (condition in node) return walkExports(node[condition])
    }
    // No runtime condition applies (types-only / browser-only / custom): the
    // loader never resolves this entry here, so it requires nothing.
  }
  addTarget(typeof pkg?.main === 'string' && pkg.main !== ''
    ? (pkg.main.startsWith('./') ? pkg.main : `./${pkg.main}`)
    : undefined)
  const exports = pkg?.exports
  if (typeof exports === 'string' || Array.isArray(exports)) walkExports(exports)
  else if (exports !== null && typeof exports === 'object') {
    const subpaths = Object.keys(exports).filter((key) => key.startsWith('.'))
    // Sugar form (`exports` is itself a condition map) vs. subpath map.
    if (subpaths.length === 0) walkExports(exports)
    else for (const key of subpaths) walkExports(exports[key])
  }
  addTarget(pkg?.dsh?.bundle?.patch)
  return [...found]
}

/**
 * Files a deployed package promises but does not have.
 *
 * The freshness checks around this one all reason about *metadata* — the
 * deployed `package.json`'s version, the source content hash, the recorded
 * install spec. None of them look at whether the bytes the manifest points at
 * actually arrived. An install that dies partway (the devbox trigger: a
 * `pnpm add` transaction interrupted mid-flight) leaves exactly that shape:
 * a readable `package.json` beside a missing `lib/`, which every metadata
 * check happily reads as healthy while the loader dies on `import` with
 * ERR_MODULE_NOT_FOUND.
 *
 * `./package.json` is skipped: the manifest was just parsed to get here.
 * @returns {string[]} missing package-relative paths; empty means healthy.
 */
/**
 * Path to one deployed package's manifest inside the profile.
 * @param {string} name npm package name, scope included.
 * @returns {string} absolute path to its deployed `package.json`.
 */
function deployedPackageJsonPath(name) {
  return path.join(PROFILE_DIR, 'node_modules', ...name.split('/'), 'package.json')
}

/**
 * The reviewed identity a compatibility artifact was produced from.
 *
 * Only the fields that pin WHAT WAS PATCHED AND FROM WHERE take part: the
 * upstream base commit and the patch hash. Version is deliberately excluded —
 * it is a label the build assigns, so two artifacts can share a version while
 * being derived from different upstream trees, which is the drift this exists
 * to catch. Returns undefined when the artifact declares no provenance, so an
 * unannotated package is reported as unknown rather than silently equal.
 * @param {object|undefined} pkg a parsed package manifest.
 * @returns {string|undefined} a comparable identity, or undefined when absent.
 */
function compatProvenanceOf(pkg) {
  const compat = pkg?.dsh_compat
  if (compat === null || typeof compat !== 'object') return undefined
  const base = typeof compat.upstreamBase === 'string' ? compat.upstreamBase : ''
  const patch = typeof compat.patchSha256 === 'string' ? compat.patchSha256 : ''
  if (base === '' && patch === '') return undefined
  return `${base}/${patch}`
}

function missingDeployedFiles(name) {
  const dir = path.join(PROFILE_DIR, 'node_modules', ...name.split('/'))
  const pkg = readJson(path.join(dir, 'package.json'))
  if (pkg === undefined) return []   // not installed at all: the version check owns that case
  // CommonJS-style tolerance: a bare `main` may address a file without its
  // extension or a directory with an index. Treat a requirement as satisfied
  // when any of those candidates exists, so legacy layouts are not condemned.
  const satisfied = (rel) => [rel, `${rel}.js`, `${rel}.mjs`, `${rel}.cjs`, `${rel}.json`, path.join(rel, 'index.js')]
    .some((candidate) => existsSync(path.join(dir, candidate)))
  return declaredRuntimeFiles(pkg)
    .filter((rel) => rel !== 'package.json' && !satisfied(rel))
}

/**
 * The spec string a remote package was installed from, as recorded in the
 * profile manifest (pnpm stores the tarball/registry URL there). Indexed by
 * package name; the entry at `name` is the one sync actually controls.
 */
function installedSpec(name) {
  const profile = readJson(path.join(PROFILE_DIR, 'package.json'))
  if (profile === undefined) return undefined
  return profile.dependencies?.[name]
}

function declaresBundle(name) {
  const pkg = readJson(path.join(PROFILE_DIR, 'node_modules', ...name.split('/'), 'package.json'))
  return pkg?.dsh?.bundle?.patch !== undefined
}

