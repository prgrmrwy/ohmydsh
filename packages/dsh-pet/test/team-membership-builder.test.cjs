'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { resolve, join } = require('node:path')
const { createHash } = require('node:crypto')
const here = resolve(__dirname, '../compat/subagent')
test('Team membership patch is pinned and shipped through the existing compatibility graph', () => {
  const template = JSON.parse(readFileSync(join(here, 'team-membership.package.template.json'), 'utf8'))
  const patch = readFileSync(join(here, 'team-membership.patch'))
  const hash = createHash('sha256').update(patch).digest('hex')
  assert.equal(template.patchSha256, hash)
  assert.deepEqual(template.packages.map(p => p.name), ['@deepseek-ai/dsh-experimental-agent-team'])
  const build = readFileSync(join(here, 'build.mjs'), 'utf8')
  const launcher = readFileSync(join(here, 'build-launcher.cjs'), 'utf8')
  assert.ok(build.includes(`teamMembershipHash !== '${hash}'`))
  for (const marker of ["['apply', '--check', teamMembershipPatchFile]", "['apply', teamMembershipPatchFile]", '...teamMembershipTemplate.packages', 'artifactTemplate.patchSha256', 'packages/experimental/agent-team/tests/team.spec.ts', 'packages/experimental/tool-agent-team/tests']) assert.ok(build.includes(marker), marker)
  for (const marker of ['team-membership.patch', 'team-membership.package.template.json', '...teamMembershipTemplate.packages', 'pkg.version !== template.version', 'pkg.dsh_compat?.patchSha256 !== template.patchSha256']) assert.ok(launcher.includes(marker), marker)
  assert.equal((patch.toString().match(/^\+.*origin === 'subagent'/gm) || []).length, 2)
  assert.doesNotMatch(patch.toString(), /subagent\/descriptor|\+.*append\(/)
})
