'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { resolve, join } = require('node:path')
const { createHash } = require('node:crypto')
const here = resolve(__dirname, '../compat/subagent')
test('model display patch is pinned, built, copied, overridden, fingerprinted and behavior-verified by the existing owner', () => {
  const template = JSON.parse(readFileSync(join(here, 'model-display.package.template.json'), 'utf8'))
  const patch = readFileSync(join(here, 'model-display.patch'))
  const hash = createHash('sha256').update(patch).digest('hex')
  assert.equal(template.patchSha256, hash)
  const build = readFileSync(join(here, 'build.mjs'), 'utf8')
  const launcher = readFileSync(join(here, 'build-launcher.cjs'), 'utf8')
  assert.ok(build.includes(`modelDisplayPatchSha256: '${hash}'`))
  assert.ok(launcher.includes(`modelDisplayPatchSha256 = '${hash}'`))
  for (const marker of ['modelDisplayPatchFile', "['apply', '--check', modelDisplayPatchFile]", "['apply', modelDisplayPatchFile]", 'model-display.vitest.config.mjs', 'modelDisplayTemplate.packages', 'model-display-artifacts']) assert.ok(build.includes(marker), marker)
  for (const marker of ['model-display.patch', 'model-display.package.template.json', 'model-display.vitest.config.mjs', 'verify-model-display.mjs', 'modelDisplayPackages', 'model-display-artifacts']) assert.ok(launcher.includes(marker), marker)
  assert.ok(launcher.includes("[join(here, 'verify-model-display.mjs'), '--graph', directory]"))
  for (const test of ['host', 'react', 'routing', 'popup']) assert.ok(launcher.includes(`model-display-${test}.spec.`), `fingerprint ${test} test`)
  assert.ok(build.includes("join(outputRoot, 'agent-artifacts', 'model-display-artifacts')"), 'formal build output must stay under the existing ignored artifacts root')
  assert.equal(template.packages.length, 5)
  assert.ok(template.packages.some(pkg => pkg.name === '@deepseek-ai/dsh-api-remotes'), 'generated Remote consumer must not retain the old response codec')
  assert.doesNotMatch(patch.toString(), /^diff --git a\/packages\/core\/agent\//m)
  assert.doesNotMatch(patch.toString(), /^diff --git a\/packages\/api\/session-controller\/src\/model-selection-projection.ts/m)
})
