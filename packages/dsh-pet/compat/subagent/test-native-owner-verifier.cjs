'use strict'
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const { spawnSync } = require('node:child_process')
const verifier = join(__dirname, 'verify-native-managed-effects.mjs')
const source = readFileSync(verifier, 'utf8')
assert.match(source, /args\[0\] !== '--graph'/)
assert.match(source, /createRequire\(join\(graph, 'package\.json'\)\)/)
assert.match(source, /Symbol\.for\('dsh\.tool\.managed-effect'\)/)
assert.match(source, /await ctx\.plugin\(toolSubagent,/)
assert.match(source, /await ctx\.plugin\(toolControl\)/)
assert.match(source, /maxDepth: 'provider-managed'/)
assert.match(source, /sendMessage/)
assert.match(source, /Tools\.defineTool\(/)
assert.match(source, /ctx\.tools\.register\(/)
assert.match(source, /await ctx\.plugin\(Loop\.default/)
assert.match(source, /supportsIsolatedQueuedTurnClaim/)
assert.match(source, /native-owner test guard denied/)
assert.match(source, /actual mounted native ownership annotations plus final tool-guard interaction/)
assert.doesNotMatch(source, /fetch\(|https?:\/\//)
const result = spawnSync(process.execPath, [verifier], { encoding: 'utf8' })
assert.equal(result.status, 2, 'missing graph argument must fail closed')
assert.match(result.stderr, /Usage: node verify-native-managed-effects\.mjs --graph \/absolute\/path\/to\/launcher/)
const badOption = spawnSync(process.execPath, [verifier, '/tmp'], { encoding: 'utf8' })
assert.equal(badOption.status, 2, 'positional graph argument must be rejected')
const validShape = spawnSync(process.execPath, [verifier, '--graph', '/tmp/nonexistent-native-graph'], { encoding: 'utf8' })
assert.notEqual(validShape.status, 2, 'documented --graph syntax must pass argument parsing')
console.log('native-owner verifier structural and CLI checks passed')
